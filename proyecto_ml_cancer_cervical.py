# Gráfico de Recall
sns.barplot(data=df_resultados, x="Modelo", y="Recall", ax=axes[0])
axes[0].set_title("Comparativa de Recall")
axes[0].set_ylim(0, 1)
for container in axes[0].containers:
    axes[0].bar_label(container, fmt='%.2f')

# Gráfico de F1-Score
sns.barplot(data=df_resultados, x="Modelo", y="F1-Score", ax=axes[1])
axes[1].set_title("Comparativa de F1-Score")
axes[1].set_ylim(0, 1)
for container in axes[1].containers:
    axes[1].bar_label(container, fmt='%.2f')

plt.tight_layout()
plt.show()

